"""Structural contracts consumed by use cases, independent of SQLite/SMTP."""
from contextlib import AbstractContextManager
from typing import Callable, Protocol


class Repository(Protocol):
    def transaction(self) -> AbstractContextManager: ...
    def message_exists(self, key: str) -> bool: ...
    def add_message(self, key: str, message: dict, received_at: str) -> bool: ...
    def messages(self) -> list[dict]: ...
    def events(self) -> list[dict]: ...
    def event_exists(self, event_id: str) -> bool: ...
    def matching_events(self, title: str, group: str) -> list[dict]: ...
    def save_event(self, event: dict, title: str, group: str) -> None: ...
    def has_delivered_jobs(self) -> bool: ...
    def pending_payloads(self) -> list[dict]: ...
    def version_floors(self) -> dict[str, int]: ...
    def begin_rebuild(self) -> None: ...
    def expire_reminders(self, now: str) -> None: ...
    def pending_count(self) -> int: ...
    def enqueue(self, event: dict, reason: str, due_at: str, suffix: str) -> None: ...
    def supersede_event_jobs(self, event_id: str) -> None: ...
    def maintain_jobs(self, stale_before: str, reminders_enabled: bool) -> None: ...
    def due_jobs(self, now: str) -> list[dict]: ...
    def claim_job(self, job_id: int, now: str) -> bool: ...
    def finish_job(self, job_id: int, status: str) -> None: ...
    def fail_job(self, job_id: int, status: str, attempts: int, error: str, due_at: str) -> None: ...
    def capture_initialized(self, group: str) -> bool: ...
    def capture_seen(self, group: str, fingerprint: str) -> bool: ...
    def mark_seen(self, group: str, fingerprint: str) -> None: ...
    def mark_capture(self, group: str, now: str) -> None: ...


class MessageProcessor(Protocol):
    def __call__(self, message: dict, config: dict, *, report: dict) -> list[dict]: ...


class MailSender(Protocol):
    def __call__(self, subject: str, body: str, config: dict, *, html_body: str | None = None) -> None: ...


RulesAnalyzer = Callable[[dict], list[dict]]
